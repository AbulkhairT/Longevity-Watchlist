/**
 * Prints the draft PR body for the latest collection run (Markdown, stdout).
 * Counts and links only: never secrets, prompts, AI replies or response bodies.
 * Record titles come from external sources, so they are sanitized and truncated.
 *
 *   npm run --silent pr:summary > "$RUNNER_TEMP/pr-body.md"
 */
import fs from "node:fs";
import path from "node:path";
import { MONITORING_DIR, readRuns } from "../src/lib/monitoring";
import { loadPipelineConfig } from "../src/lib/pipeline-config";
import { AI_DIR, CANDIDATES_DIR, LATEST_RUN_FILE, REJECTED_DIR } from "../src/pipeline/paths";
import { Candidate } from "../src/pipeline/types";

/** Neutralize Markdown/HTML and mentions in untrusted text. */
export function safe(s: string, max = 140): string {
  const t = s
    .replace(/[\r\n]+/g, " ")
    .replace(/[<>`*_[\]|\\#]/g, " ")
    .replace(/@/g, "(at)")
    .replace(/\s+/g, " ")
    .trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
}

function main() {
  const cfg = loadPipelineConfig();
  const runId = fs.existsSync(LATEST_RUN_FILE) ? fs.readFileSync(LATEST_RUN_FILE, "utf8").trim() : null;
  const run = readRuns(MONITORING_DIR).find((r) => r.runId === runId) ?? null;
  const candidates = fs.existsSync(CANDIDATES_DIR)
    ? fs.readdirSync(CANDIDATES_DIR).filter((f) => f.endsWith(".json")).map((f) => Candidate.parse(JSON.parse(fs.readFileSync(path.join(CANDIDATES_DIR, f), "utf8"))))
    : [];
  const status = (id: string) => (fs.existsSync(path.join(AI_DIR, `${id}.json`)) ? "AI draft" : fs.existsSync(path.join(REJECTED_DIR, `${id}.json`)) ? "AI reply rejected" : "manual");
  const fromRun = candidates.filter((c) => c.runId === runId);

  const out: string[] = [];
  out.push("## Research drafts (not published)", "");
  out.push(
    "> **Nothing here is published.** These are collected records and optional AI suggestions under `drafts/`. Merging this PR publishes nothing. A person must read each source, edit a claim draft, and run `npm run approve -- <claim-id> --reviewer \"Name\" --reason \"...\"`.",
    "",
  );
  if (!run) {
    out.push("No monitoring run was recorded for this workflow run.", "");
  } else {
    const u = run.usage;
    out.push(`**Run** \`${run.runId}\` · started ${run.startedAt} · finished ${run.finishedAt}`, "");
    out.push("| Intervention | Papers screened | Trial records checked | New candidates | Duplicates | Off-topic | Updates published | Grade changes |");
    out.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
    for (const [iv, c] of Object.entries(run.interventions)) {
      const kept = c.candidatesFound - c.rejectedDuplicate - c.rejectedIrrelevant;
      out.push(`| ${safe(iv, 40)} | ${c.papersScreened} | ${c.trialRecordsChecked} | ${kept} | ${c.rejectedDuplicate} | ${c.rejectedIrrelevant} | ${c.updatesPublished} | ${c.gradeChanges} |`);
    }
    out.push("");
    if (u) {
      out.push(`**Requests:** PubMed ${u.pubmedRequests} (cap ${cfg.collection.pubmed.maxRequestsPerRun}), ClinicalTrials.gov ${u.clinicaltrialsRequests} (cap ${cfg.collection.clinicaltrials.maxRequestsPerRun}), transient retries ${u.transientRetries}.`);
      out.push(`**Candidates this run:** ${u.candidatesNew} new, ${u.candidatesRevised} revised trial records.`);
      out.push(
        u.aiEnabled
          ? `**AI drafting (${cfg.ai.model}):** ${u.aiCandidatesSent} candidates sent (cap ${cfg.ai.maxCandidatesPerRun}), ${u.aiRequests} requests (cap ${cfg.ai.maxRequestsPerRun}), about ${u.aiPromptTokens} input and ${u.aiCompletionTokens} output tokens, ${u.aiDrafted} drafted, ${u.aiRejected} rejected.`
          : "**AI drafting:** off. All candidates are for manual preparation.",
      );
      if (u.aiStopReason) out.push(`**AI stop reason:** ${safe(u.aiStopReason, 300)}`);
      out.push("");
    }
    if (run.notes.length) {
      out.push("**Notes and errors**", "");
      for (const n of run.notes) out.push(`- ${safe(n, 300)}`);
      out.push("");
    }
  }
  out.push(`### Candidates from this run (${fromRun.length}; ${candidates.length} waiting in total)`, "");
  if (!fromRun.length) out.push("None.");
  for (const c of fromRun.slice(0, 60)) {
    const id = c.identifiers.pmid ? `PMID ${c.identifiers.pmid}` : c.identifiers.nct;
    out.push(`- [${id}](${c.url}) · ${c.recordType} · ${c.claimIds.join(", ")} · ${status(c.id)}: ${safe(c.title)}`);
  }
  if (fromRun.length > 60) out.push(`- …and ${fromRun.length - 60} more in \`drafts/candidates/\`.`);
  out.push("", "<sub>Generated by the Collect research workflow. Search queries in config/searches.json still need human tuning.</sub>", "");
  process.stdout.write(out.join("\n"));
}

main();
